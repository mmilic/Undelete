const wchar_t *Deutsch::translate(const wchar_t *szEnglish) {
    const std::unordered_map<std::wstring, const wchar_t *> &table = GermanTable();
    std::unordered_map<std::wstring, const wchar_t *>::const_iterator it = table.find(szEnglish);
    return it != table.end() ? it->second : szEnglish;
}
